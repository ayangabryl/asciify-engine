# Rasterises printable ASCII from DejaVu Sans Mono (Bitstream Vera licence: free to use, copy and modify) into 16 × 32
# alpha masks for the command line's PNG, GIF and video output, and writes src/cli/glyph-atlas.ts. Block elements, shades
# and braille are drawn as shapes at run time, so they are not here. Needs Pillow: python3 scripts/build-cli-glyphs.py
import base64, zlib, os
from PIL import Image, ImageDraw, ImageFont

W, H, FIRST, COUNT = 16, 32, 32, 95
font_path = '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf'
# The font size whose advance is the cell's width.
size = 32
font = ImageFont.truetype(font_path, size)
while font.getlength('M') > W + 0.01:
    size -= 0.25
    font = ImageFont.truetype(font_path, size)
ascent, descent = font.getmetrics()
top = (H - (ascent + descent)) / 2
masks = bytearray()
for code in range(FIRST, FIRST + COUNT):
    # Drawn four times larger and averaged down, for smooth edges.
    big = ImageFont.truetype(font_path, size * 4)
    img = Image.new('L', (W * 4, H * 4), 0)
    ImageDraw.Draw(img).text((0, top * 4), chr(code), font=big, fill=255)
    masks += img.resize((W, H), Image.BOX).tobytes()
packed = base64.b64encode(zlib.compress(bytes(masks), 9)).decode('ascii')
out = os.path.join(os.path.dirname(__file__), '..', 'src', 'cli', 'glyph-atlas.ts')
with open(out, 'w') as f:
    f.write('// Generated by scripts/build-cli-glyphs.py from DejaVu Sans Mono (Bitstream Vera licence). Do not edit.\n')
    f.write('/** Printable ASCII as 16 × 32 alpha masks, zlib-compressed and base64-encoded, one after another from U+0020. */\n')
    f.write(f"export const GLYPH_ATLAS = {{ width: {W}, height: {H}, first: {FIRST}, count: {COUNT}, data: '{packed}' }};\n")
print('wrote', out, len(packed), 'base64 chars; font size', size)
