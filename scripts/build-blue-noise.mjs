// Offline, deterministic void-and-cluster ranking. No generation runs in an app.
// Algorithm reference: https://cv.ulichney.com/papers/1993-void-cluster.pdf
import { writeFile } from 'node:fs/promises';

const size = 64, count = size * size, seedCount = Math.floor(count * .1);
const occupied = new Uint8Array(count), energy = new Float64Array(count);
const ranks = new Uint16Array(count), kernel = [];
for (let y = -6; y <= 6; y++) for (let x = -6; x <= 6; x++) {
  kernel.push([x, y, Math.exp(-(x * x + y * y) / (2 * 1.5 ** 2))]);
}
let seed = 0x41534349;
function random() {
  seed ^= seed << 13; seed ^= seed >>> 17; seed ^= seed << 5;
  return (seed >>> 0) / 4294967296;
}
function set(index, value) {
  const delta = value - occupied[index];
  occupied[index] = value;
  const x = index % size, y = Math.floor(index / size);
  for (const [dx, dy, weight] of kernel) {
    energy[((y + dy + size) % size) * size + (x + dx + size) % size] += delta * weight;
  }
}
function select(value, largest) {
  let index = -1, best = largest ? -Infinity : Infinity;
  for (let i = 0; i < count; i++) if (occupied[i] === value &&
      (largest ? energy[i] > best : energy[i] < best)) {
    index = i; best = energy[i];
  }
  return index;
}
for (let i = 0; i < seedCount;) {
  const index = Math.floor(random() * count);
  if (!occupied[index]) { set(index, 1); i++; }
}
let relaxed = false;
for (let iteration = 0; iteration < count * 20; iteration++) {
  const cluster = select(1, true); set(cluster, 0);
  const voidIndex = select(0, false); set(voidIndex, 1);
  if (cluster === voidIndex) { relaxed = true; break; }
}
if (!relaxed) throw new Error('Void-and-cluster relaxation did not converge.');
const prototype = occupied.slice(), prototypeEnergy = energy.slice();
// Lower ranks remove the densest minority clusters. Higher ranks fill voids.
for (let rank = seedCount - 1; rank >= 0; rank--) {
  const cluster = select(1, true); ranks[cluster] = rank; set(cluster, 0);
}
occupied.set(prototype); energy.set(prototypeEnergy);
for (let rank = seedCount; rank < count; rank++) {
  const voidIndex = select(0, false); ranks[voidIndex] = rank; set(voidIndex, 1);
}
const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
const encoded = [...ranks].map(rank => alphabet[rank >>> 6] + alphabet[rank & 63]).join('');
const rows = Array.from({length: size}, (_, y) => '  ' + JSON.stringify(encoded.slice(y * size * 2, (y + 1) * size * 2)));
await writeFile('src/studio/blue-noise.ts', `// Generated by scripts/build-blue-noise.mjs. Seed 0x41534349; toroidal 64×64; sigma 1.5.\n// Two six-bit characters per rank. The decoded mask occupies 8 KiB.\nexport const BLUE_NOISE_SIZE = ${size};\nconst alphabet = '${alphabet}';\nconst encoded =\n${rows.join(' +\n')};\nexport const BLUE_NOISE_RANKS = new Uint16Array(${count});\nfor (let i = 0; i < BLUE_NOISE_RANKS.length; i++) {\n  BLUE_NOISE_RANKS[i] = (alphabet.indexOf(encoded[i * 2]) << 6) | alphabet.indexOf(encoded[i * 2 + 1]);\n}\n`);
console.log(`Generated ${size}×${size} blue-noise rank tile.`);
