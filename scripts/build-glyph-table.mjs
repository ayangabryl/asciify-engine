// Builds src/headless/glyph-table.ts: how much ink each printable ASCII character puts in each part of its cell, measured
// from a real monospace font (DejaVu Sans Mono, the Bitstream Vera design behind Menlo and many terminal defaults).
// node scripts/build-glyph-table.mjs   (needs Playwright's Chromium and the font installed)
import { writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const FONT = process.env.GLYPH_FONT ?? 'DejaVu Sans Mono';
const COLS = 3, ROWS = 5, SIZE = 120, INK_SIZE = 14;
const CHARS = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)).join('');

const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  const result = await page.evaluate(async ({ FONT, COLS, ROWS, SIZE, INK_SIZE, CHARS }) => {
    const font = `${SIZE}px "${FONT}"`;
    await document.fonts.load(font);
    const probe = document.createElement('canvas').getContext('2d');
    probe.font = font;
    const m = probe.measureText('M');
    const width = Math.round(m.width), ascent = Math.round(m.fontBoundingBoxAscent), height = Math.round(m.fontBoundingBoxAscent + m.fontBoundingBoxDescent);
    const canvas = document.createElement('canvas'); canvas.width = width; canvas.height = height;
    const pen = canvas.getContext('2d', { willReadFrequently: true });
    const coverage = [];
    for (const char of CHARS) {
      pen.fillStyle = '#000'; pen.fillRect(0, 0, width, height);
      pen.fillStyle = '#fff'; pen.font = font; pen.textBaseline = 'alphabetic';
      pen.fillText(char, 0, ascent);
      const { data } = pen.getImageData(0, 0, width, height);
      for (let r = 0; r < ROWS; r++) for (let c = 0; c < COLS; c++) {
        const x0 = Math.round(c * width / COLS), x1 = Math.round((c + 1) * width / COLS);
        const y0 = Math.round(r * height / ROWS), y1 = Math.round((r + 1) * height / ROWS);
        let sum = 0;
        for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) sum += data[(y * width + x) * 4] / 255;
        coverage.push(Math.round(sum / ((x1 - x0) * (y1 - y0)) * 255));
      }
    }
    // The light each glyph actually gives off at reading size: at 14px anti-aliased edges are gamma-encoded, so a glyph emits
    // noticeably less light than its large outline suggests. Measured as linear light over many copies at shifting offsets.
    const small = `${INK_SIZE}px "${FONT}"`;
    await document.fonts.load(small);
    probe.font = small;
    const sm = probe.measureText('M'), sw = sm.width, sh = sm.fontBoundingBoxAscent + sm.fontBoundingBoxDescent;
    const sheet = document.createElement('canvas'); sheet.width = Math.ceil(sw * 64); sheet.height = Math.ceil(sh * 4);
    const sp = sheet.getContext('2d', { willReadFrequently: true });
    const linear = v => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
    const ink = [];
    for (const char of CHARS) {
      sp.fillStyle = '#000'; sp.fillRect(0, 0, sheet.width, sheet.height);
      sp.fillStyle = '#fff'; sp.font = small;
      for (let r = 0; r < 4; r++) for (let i = 0; i < 64; i++) sp.fillText(char, i * sw + (r * 0.25), r * sh + sm.fontBoundingBoxAscent);
      const { data } = sp.getImageData(0, 0, sheet.width, sheet.height);
      let light = 0;
      for (let i = 0; i < data.length; i += 4) light += linear(data[i] / 255);
      ink.push(Math.round(light / (data.length / 4) * 1000) / 1000);
    }
    return { coverage, ink, aspect: height / width, family: FONT, width, height };
  }, { FONT, COLS, ROWS, SIZE, INK_SIZE, CHARS });
  if (result.coverage.every(v => v === 0)) throw new Error(`Font ${FONT} drew nothing.`);
  const b64 = Buffer.from(Uint8Array.from(result.coverage)).toString('base64');
  await writeFile(new URL('../src/headless/glyph-table.ts', import.meta.url), `// Generated by scripts/build-glyph-table.mjs from ${result.family}. Do not edit.
/** Sub-cells per glyph, across and down. */
export const GLYPH_COLS = ${COLS}, GLYPH_ROWS = ${ROWS};
/** Printable ASCII, space to tilde. */
export const GLYPH_CHARS = ${JSON.stringify(CHARS)};
/** Cell height over width in the measured font (${result.width}x${result.height} at ${SIZE}px). */
export const GLYPH_CELL_ASPECT = ${result.aspect.toFixed(4)};
/** Ink coverage, 0-255, per glyph then per sub-cell (row by row), base64: where each glyph puts its strokes. */
export const GLYPH_COVERAGE = '${b64}';
/** Light each glyph gives off at ${INK_SIZE}px, as a share of its cell lit fully (linear light, anti-aliasing included). */
export const GLYPH_INK = [${result.ink.join(',')}];
`);
  console.log(`Glyph table: ${CHARS.length} glyphs, ${COLS}x${ROWS} sub-cells, cell aspect ${result.aspect.toFixed(3)} (${result.family}).`);
} finally {
  await browser.close();
}
